    'class SobelLoss(nn.Module):\n',
    '    # 반도체 패턴 수평/수직 에지 보존 손실\n',
    '    def __init__(self) -> None:\n',
    '        super().__init__()\n',
    '        kx = torch.tensor([[-1., 0., 1.], [-2., 0., 2.], [-1., 0., 1.]]).view(1, 1, 3, 3)\n',
    '        ky = torch.tensor([[-1., -2., -1.], [0., 0., 0.], [1., 2., 1.]]).view(1, 1, 3, 3)\n',
    '        self.register_buffer("kx", kx)\n',
    '        self.register_buffer("ky", ky)\n',
    '\n',
    '    def forward(self, pred: Tensor, target: Tensor) -> Tensor:\n',
    '        gx_p = functional.conv2d(pred, self.kx.to(pred.device), padding=1)\n',
    '        gy_p = functional.conv2d(pred, self.ky.to(pred.device), padding=1)\n',
    '        gx_t = functional.conv2d(target, self.kx.to(target.device), padding=1)\n',
    '        gy_t = functional.conv2d(target, self.ky.to(target.device), padding=1)\n',
    '        return functional.l1_loss(gx_p, gx_t) + functional.l1_loss(gy_p, gy_t)\n',
    '\n',
    '\n',
    'sobel_loss = SobelLoss()\n',
    '\n',
    '\n',
    'def get_lr(epoch: int, spec: dict) -> float:\n',
    '    # 1-indexed epoch. warmup 후 cosine\n',
    '    lr, total = spec["lr"], spec["epochs"]\n',
    '    warm = spec.get("warmup", 1)\n',
    '    if epoch <= warm:\n',
    '        return lr * epoch / max(1, warm)\n',
    '    t = (epoch - warm) / max(1, total - warm)\n',
    '    return lr * (spec.get("lr_min_ratio", 0.01) + (1 - spec.get("lr_min_ratio", 0.01)) * 0.5 * (1 + math.cos(math.pi * t)))\n',
    '\n',
    '\n',
    'def compute_loss(pred: Tensor, target: Tensor, measure: Tensor, spec: dict) -> Tensor:\n',
    '    base = spec.get("loss_model", "l1")\n',
    '    loss = functional.l1_loss(pred, target) if base == "l1" else functional.mse_loss(pred, target)\n',
    '\n',
    '    # SSIM Loss\n',
    '    w_ssim = spec.get("ssim_weight", 0.5)\n',
    '    if w_ssim > 0:\n',
    '        loss = loss + w_ssim * (1.0 - calculate_ssim(pred.clamp(0, 1), target.clamp(0, 1)).mean())\n',
    '\n',
    '    # Sobel Edge Loss\n',
    '    w_sobel = spec.get("sobel_weight", 0.1)\n',
    '    if w_sobel > 0:\n',
    '        loss = loss + w_sobel * sobel_loss(pred, target)\n',
    '\n',
    '    # Forward Physics Consistency (DC) Loss\n',
    '    w_dc = spec.get("dc_weight", 0.02)\n',
    '    if w_dc > 0 and spec["target"] == "label":\n',
    '        with torch.autocast(device_type=pred.device.type, enabled=False):\n',
    '            loss = loss + w_dc * functional.l1_loss(dipole_forward(pred.float()), measure.float())\n',
    '    return loss\n',
    '\n',
    '\n',
    'def model_forward(model: nn.Module, measure: Tensor, spec: dict) -> Tensor:\n',
    '    return model(measure)\n',
    '\n',
    '\n',
    '@torch.no_grad()\n',
