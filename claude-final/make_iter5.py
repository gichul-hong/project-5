    '    # Squeeze-and-Excitation 채널 어텐션 모듈\n',
    '    def __init__(self, channels: int, reduction: int = 8) -> None:\n',
    '        super().__init__()\n',
    '        self.fc = nn.Sequential(\n',
    '            nn.AdaptiveAvgPool2d(1),\n',
    '            nn.Conv2d(channels, max(4, channels // reduction), kernel_size=1),\n',
    '            nn.SiLU(inplace=True),\n',
    '            nn.Conv2d(max(4, channels // reduction), channels, kernel_size=1),\n',
    '            nn.Sigmoid(),\n',
    '        )\n',
    '\n',
    '    def forward(self, x: Tensor) -> Tensor:\n',
    '        return x * self.fc(x)\n',
    '\n',
    '\n',
    'class ResConvBlock(nn.Module):\n',
    '    # Residual Block with GroupNorm, SiLU and SE-Attention\n',
    '    def __init__(self, in_chans: int, out_chans: int) -> None:\n',
    '        super().__init__()\n',
    '        self.conv = nn.Sequential(\n',
    '            nn.Conv2d(in_chans, out_chans, kernel_size=3, padding=1),\n',
    '            nn.GroupNorm(4, out_chans),\n',
    '            nn.SiLU(inplace=True),\n',
    '            nn.Conv2d(out_chans, out_chans, kernel_size=3, padding=1),\n',
    '            nn.GroupNorm(4, out_chans),\n',
